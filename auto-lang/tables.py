#!/usr/bin/env python3
"""The Unicode script table of auto-lang's ports, one per language, made
from the original's own table, `upstream/script-ranges.lua` (generated
upstream from the Unicode 15.0.0 Character Database; the data is
Unicode's, under `upstream/UNICODE-LICENSE`), so that the four ports and
the original classify every code point alike.

    python3 auto-lang/tables.py           writes the four tables
    python3 auto-lang/tables.py --check   fails if one is not what it writes

Writes `python/script_ranges.py`, `ts/script-ranges.ts`,
`rust/src/script_ranges.rs` and `julia/script-ranges.jl`: the scripts'
names, the right-to-left ones, every code point range of a script's own
(`strong`, sorted, with its script), the ranges of Script=Inherited, and
each script's Script_Extensions ranges (`ext`), as the original's table
has them.
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "upstream" / "script-ranges.lua"


def read() -> dict:
    """The Lua table's parts, by a pattern each: the file is generated, one
    part per line or block, as its generator writes it."""
    text = SOURCE.read_text(encoding="utf-8")
    version = re.search(r'version = "([^"]+)"', text)[1]

    def names(key: str) -> list[str]:
        line = re.search(rf"^  {key} = \{{(.*)\}},$", text, re.M)[1]
        return re.findall(r"(\w+) = true", line)

    def ranges(body: str) -> list[tuple[int, int]]:
        return [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-F]+),0x([0-9A-F]+)\}", body)]

    strong_body = re.search(r"^  strong = \{\n(.*?)^  \},$", text, re.M | re.S)[1]
    strong = [(int(a, 16), int(b, 16), s) for a, b, s in re.findall(r'\{0x([0-9A-F]+),0x([0-9A-F]+),"(\w+)"\}', strong_body)]
    inherited = ranges(re.search(r"^  inherited = (.*),$", text, re.M)[1])
    ext_body = re.search(r"^  ext = \{\n(.*?)^  \},$", text, re.M | re.S)[1]
    ext = {name: ranges(body) for name, body in re.findall(r"^    (\w+) = (\{.*\}),$", ext_body, re.M)}
    table = {"version": version, "names": names("names"), "rtl": names("rtl"), "strong": strong, "inherited": inherited, "ext": ext}
    check(table)
    return table


def check(t: dict) -> None:
    """What the ports' searches take for granted: sorted ranges that don't
    overlap, of named scripts."""
    for rs in [[(a, b) for a, b, _ in t["strong"]], t["inherited"], *t["ext"].values()]:
        assert all(a <= b for a, b in rs) and all(b < c for (_, b), (c, _) in zip(rs, rs[1:])), "unsorted ranges"
    names = set(t["names"])
    assert {s for *_, s in t["strong"]} <= names and set(t["rtl"]) <= names and set(t["ext"]) <= names
    assert len(t["strong"]) > 500 and len(t["ext"]) > 50  # (the whole table was read)


HEADER = "Generated by auto-lang/tables.py from upstream/script-ranges.lua, the original's table of the Unicode {version} Character Database (Unicode's data: upstream/UNICODE-LICENSE); do not edit."


def python(t: dict) -> str:
    def rs(ranges):
        return "(" + ", ".join(f"(0x{a:04X}, 0x{b:04X})" for a, b in ranges) + ",)"

    out = [f'"""{HEADER.format(**t)}"""', "", f'VERSION = "{t["version"]}"']
    out.append("NAMES = frozenset({" + ", ".join(f'"{n}"' for n in t["names"]) + "})")
    out.append("RTL = frozenset({" + ", ".join(f'"{n}"' for n in t["rtl"]) + "})")
    out.append("# (first, last, script), sorted")
    out.append("STRONG = (")
    out += [f'    (0x{a:04X}, 0x{b:04X}, "{s}"),' for a, b, s in t["strong"]]
    out.append(")")
    out.append(f"INHERITED = {rs(t['inherited'])}")
    out.append("EXT = {")
    out += [f'    "{n}": {rs(r)},' for n, r in t["ext"].items()]
    out.append("}")
    return "\n".join(out) + "\n"


def typescript(t: dict) -> str:
    def rs(ranges):
        return "[" + ", ".join(f"[0x{a:04X}, 0x{b:04X}]" for a, b in ranges) + "]"

    out = [f"// {HEADER.format(**t)}", "", "type Ranges = readonly (readonly [number, number])[];", ""]
    out.append(f'export const VERSION = "{t["version"]}";')
    out.append("export const NAMES: ReadonlySet<string> = new Set([" + ", ".join(f'"{n}"' for n in t["names"]) + "]);")
    out.append("export const RTL: ReadonlySet<string> = new Set([" + ", ".join(f'"{n}"' for n in t["rtl"]) + "]);")
    out.append("/** [first, last, script], sorted. */")
    out.append("export const STRONG: readonly (readonly [number, number, string])[] = [")
    out += [f'  [0x{a:04X}, 0x{b:04X}, "{s}"],' for a, b, s in t["strong"]]
    out.append("];")
    out.append(f"export const INHERITED: Ranges = {rs(t['inherited'])};")
    out.append("export const EXT: ReadonlyMap<string, Ranges> = new Map([")
    out += [f'  ["{n}", {rs(r)}],' for n, r in t["ext"].items()]
    out.append("]);")
    return "\n".join(out) + "\n"


def rust(t: dict) -> str:
    def rs(ranges):
        return "&[" + ", ".join(f"(0x{a:04X}, 0x{b:04X})" for a, b in ranges) + "]"

    out = [f"//! {HEADER.format(**t)}", ""]
    out.append(f'pub const VERSION: &str = "{t["version"]}";')
    out.append("/// Sorted, for a binary search.")
    out.append("#[rustfmt::skip]")
    out.append("pub const NAMES: &[&str] = &[" + ", ".join(f'"{n}"' for n in sorted(t["names"])) + "];")
    out.append("/// Sorted.")
    out.append("#[rustfmt::skip]")
    out.append("pub const RTL: &[&str] = &[" + ", ".join(f'"{n}"' for n in sorted(t["rtl"])) + "];")
    out.append("/// (first, last, script), sorted.")
    out.append("#[rustfmt::skip]")
    out.append("pub const STRONG: &[(u32, u32, &str)] = &[")
    out += [f'    (0x{a:04X}, 0x{b:04X}, "{s}"),' for a, b, s in t["strong"]]
    out.append("];")
    out.append("#[rustfmt::skip]")
    out.append(f"pub const INHERITED: &[(u32, u32)] = {rs(t['inherited'])};")
    out.append("/// Each script's ranges, by name, sorted.")
    out.append("#[rustfmt::skip]")
    out.append("pub const EXT: &[(&str, &[(u32, u32)])] = &[")
    out += [f'    ("{n}", {rs(r)}),' for n, r in sorted(t["ext"].items())]
    out.append("];")
    return "\n".join(out) + "\n"


def julia(t: dict) -> str:
    # (eight hex digits: a UInt32 each, whatever the value)
    def rs(ranges):
        return "[" + ", ".join(f"(0x{a:08X}, 0x{b:08X})" for a, b in ranges) + "]"

    out = [f"# {HEADER.format(**t)}", ""]
    out.append(f'const VERSION = "{t["version"]}"')
    out.append("const NAMES = Set([" + ", ".join(f'"{n}"' for n in t["names"]) + "])")
    out.append("const RTL = Set([" + ", ".join(f'"{n}"' for n in t["rtl"]) + "])")
    out.append("# (first, last, script), sorted")
    out.append("const STRONG = Tuple{UInt32, UInt32, String}[")
    out += [f'    (0x{a:08X}, 0x{b:08X}, "{s}"),' for a, b, s in t["strong"]]
    out.append("]")
    out.append(f"const INHERITED = Tuple{{UInt32, UInt32}}{rs(t['inherited'])}")
    out.append("const EXT = Dict{String, Vector{Tuple{UInt32, UInt32}}}(")
    out += [f'    "{n}" => {rs(r)},' for n, r in t["ext"].items()]
    out.append(")")
    return "\n".join(out) + "\n"


TARGETS = {
    "python/script_ranges.py": python,
    "ts/script-ranges.ts": typescript,
    "rust/src/script_ranges.rs": rust,
    "julia/script-ranges.jl": julia,
}


def main() -> int:
    table = read()
    stale = []
    for path, make in TARGETS.items():
        text = make(table)
        if "--check" in sys.argv[1:]:
            if (HERE / path).read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            (HERE / path).write_text(text, encoding="utf-8")
    if stale:
        print(f"not as auto-lang/tables.py writes them: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
